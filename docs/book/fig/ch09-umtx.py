def stepb(y, h, n, lines, cls="wu", col="#9a6b2f"):
    f.box(cls, B - 110, y, 220, h, 3); f.num(B - 96, y + 14, n, col)
    for i, t in enumerate(lines): f.text(B - 82, y + 18 + i * 14, t, "s")
