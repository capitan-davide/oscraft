from svg import Fig
f = Fig(800, 330)
def proc(x, y, w, h, title, prog, cls="u"):
    f.box(cls, x, y, w, h); f.text(x + w / 2, y + 18, title, "b c")
    f.box("k" if prog == "sh" else "g", x + 10, y + 26, w - 20, 22, 3); f.text(x + w / 2, y + 41, "program: " + prog, "s c")
# left: fork + exec
f.text(200, 24, "fork(), then exec()", "h c")
proc(20, 44, 130, 58, "parent", "sh")
f.arrow([(85, 102), (85, 136)]); f.num(100, 120, 1); f.text(114, 124, "fork(): copy everything", "s")
proc(20, 138, 130, 58, "child", "sh")
f.text(160, 160, "same memory contents,", "s"); f.text(160, 174, "same open files", "s")
f.arrow([(85, 196), (85, 222)]); f.num(100, 210, 2); f.text(114, 214, "the child rearranges itself:", "s")
f.text(114, 228, "redirects output, changes directory", "s")
f.arrow([(85, 236), (85, 258)]); f.num(100, 250, 3)
f.text(114, 254, "exec(): replace the program", "s")
proc(20, 260, 130, 58, "child", "ls")
f.text(160, 282, "the copy of step 1", "s red"); f.text(160, 296, "is thrown away", "s red")
f.line([(400, 16), (400, 318)], "life")
# right: spawn
f.text(600, 24, "spawn()", "h c")
proc(420, 44, 130, 58, "parent", "sh")
f.box("w", 580, 44, 200, 88, 3); f.text(680, 62, "the request says:", "b c")
f.lines(680, 80, ["which program, its arguments,", "which descriptors the child gets,", "its directory, signals, group"], "s c", 15)
f.line([(550, 73), (580, 73)])
f.arrow([(485, 102), (485, 258)]); f.num(500, 180, 1); f.text(514, 184, "spawn(): a new process that", "s")
f.text(514, 198, "starts in the new program", "s")
proc(420, 260, 130, 58, "child", "ls")
f.text(560, 282, "nothing copied, but only what", "s"); f.text(560, 296, "the request can express", "s")
f.save("ch18-fork-spawn.svg")
