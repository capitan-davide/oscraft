from svg import Fig
f = Fig(800, 430)
P, S = 150, 560
f.box("u", P - 110, 16, 220, 44); f.text(P, 35, "a program", "b c"); f.text(P, 51, "its C library", "s c")
f.box("u", S - 150, 16, 300, 44); f.text(S, 35, "a resource manager", "b c"); f.text(S, 51, "owns the names below /data", "s c")
f.line([(P, 60), (P, 415)], "life"); f.line([(S, 60), (S, 415)], "life")
def step(n, y, x0, x1, text, cls="lnk", m="ak", col="#2c5d9b"):
    f.arrow([(x0, y), (x1, y)], cls, m)
    f.num(min(x0, x1) + 22, y - 13, n, col); f.text(min(x0, x1) + 38, y - 9, text, "s")
f.text(P - 110, 84, 'fd = open("/data/log", O_RDONLY)', "ms")
step(1, 118, P, S - 2, 'connect message: open "log", for reading')
f.box("y", S - 130, 126, 260, 46, 3)
f.text(S, 144, "finds the file, checks access, creates", "s c")
f.text(S, 160, "state for this open: position 0, read-only", "s c")
step(2, 200, S, P + 2, "accepted: the new connection is fd", "lng", "ag", "#3e7b34")
f.text(P - 110, 232, "read(fd, buf, 100)", "ms")
step(3, 262, P, S - 2, "I/O message on fd: read 100 bytes (no path)")
f.box("y", S - 130, 270, 260, 30, 3)
f.text(S, 289, "state of this connection: position 0 -> 100", "s c")
step(4, 328, S, P + 2, "100 bytes", "lng", "ag", "#3e7b34")
f.text(P - 110, 360, "close(fd)", "ms")
step(5, 388, P, S - 2, "I/O message on fd: close")
f.box("w", S - 130, 396, 260, 26, 3)
f.text(S, 413, "the state is freed; the file remains", "s c")
f.save("ch22-connect-io.svg")
