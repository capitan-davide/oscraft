#!/bin/sh
# A FreeBSD kernel subsystem as a library for an OsCraft server: libbsdnet.a
# (the network stack, netd), libbsdusb.a (the USB core, usbd). Run inside
# FreeBSD's build environment:
#   build-bsdlib.sh <name> <source> <output dir> <bsdkern kern dir> <libc.a>
#                   <subsystem's sources, a regex> [generated objects...]
# The configuration tools/freebsd/conf/OSCRAFT_<NAME> lets config(8) pick
# the sources and write the opt_*.h headers; the objects are compiled as the
# kernel's, and only the subsystem's archived, with bsdkern's C part (which
# reaches into FreeBSD's structures) compiled the same way: bsdkern supplies
# the rest of the kernel; $EXCLUDE (a regex) leaves sources out. Names the
# libc has too are renamed bsd_*. Also
# saved: the flags and renames, for modules built against the library.
set -eu
name=$1
src=$2
out=$3
bsdkern=$4
libc=$5
subsystem=$6
shift 6
upper=$(echo "$name" | sed 's/^bsd//' | tr a-z A-Z)
conf=$(cd "$(dirname "$0")" && pwd)/conf/OSCRAFT_$upper
compile=$out/$name-compile
rm -rf "$compile"
mkdir -p "$compile"
(cd "$src/sys/arm64/conf" && config -d "$compile" -s "$src/sys" "$conf")
cd "$compile"
grep -oE '\$S/[A-Za-z0-9_/.-]+\.[cS]' Makefile | sort -u | sed 's|\$S/||' |
    grep -E "$subsystem|$(cat "$bsdkern/keep")" |
    { if [ -n "${EXCLUDE:-}" ]; then grep -vE "$EXCLUDE"; else cat; fi; } > sources
objects=$(sed -e 's|.*/||' -e 's/\.[cS]$/.o/' sources)
# Generated by config's Makefile: the interfaces' objects (from the .m
# files), archived, and headers the server's modules include (usbdevs.h).
generated=$(for g in "$@"; do case $g in *.o) ;; *) echo "$g" ;; esac; done)
objects="$objects $(for g in "$@"; do case $g in *.o) echo "$g" ;; esac; done)"
KERNBUILDDIR=$compile make -j"${JOBS:-16}" -DNO_MODULES $objects $generated > build.log 2>&1 || {
    grep 'error:' build.log >&2 || true
    exit 1
}
flags=$(KERNBUILDDIR=$compile make -DNO_MODULES -V CFLAGS)
# bsdkern's generic part, then the server's own glue ($GLUE: netd's sockets).
for c in "$bsdkern"/*.c ${GLUE:+"$GLUE"/*.c}; do
    o=bsdkern_$(basename "$c" .c).o
    ${CC:-cc} -c $flags -I"$bsdkern" "$c" -o "$o" 2>> build.log || {
        grep 'error:' build.log >&2 || true
        exit 1
    }
    objects="$objects $o"
done
# The kernel's names that are libc's too, in the program that links both.
${NM:-nm} -g --defined-only $objects 2>/dev/null | awk 'NF==3 && $2 != "U" {print $3}' | sort -u > ours
lib=$(dirname "$libc")
${NM:-nm} -g --defined-only "$libc" "$lib/libm.a" "$lib/libsys.a" "$lib/libthr.a" 2>/dev/null | awk 'NF==3 {print $3}' | sort -u > theirs
comm -12 ours theirs | sed 's/.*/& bsd_&/' > renames
echo "lib$name.a: $(wc -l < renames) names renamed"
for o in $objects; do
    ${OBJCOPY:-objcopy} --redefine-syms=renames "$o"
done
echo "$flags" > "$out/$name.cflags"
cp renames "$out/$name.renames"
rm -f "$out/lib$name.a"
${AR:-ar} rcs "$out/lib$name.a" $objects
echo "lib$name.a: $(wc -l < sources) sources"
