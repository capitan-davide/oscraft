//! FreeBSD's `libsys` for OsCraft.
//!
//! On FreeBSD, `libsys.so` holds the system-call stubs: for every call
//! `name` a function `__sys_name` that traps into the kernel, with
//! `_name` and, unless the threading library interposes it, `name` as
//! weak aliases, and `cerror`, which stores a failed call's error number
//! through `__error()` and returns -1. FreeBSD's libc, libthr and dynamic
//! loader are built on those symbols and nothing lower.
//!
//! This crate provides the same symbols over OsCraft: each is a QNX kernel
//! call or a message to a server (the process manager, a resource
//! manager), as QNX's own libc would make it, with the error numbers
//! turned into FreeBSD's. FreeBSD's libc and loader, built from source
//! against it, then run on OsCraft unchanged.
//!
//! - [`kercall`]: the trap and `MsgSendv()`;
//! - [`errno`]: `__error()` and the translation of QNX's numbers;
//! - [`io`]: the file-descriptor calls, as I/O messages;
//! - [`path`]: the connect protocol, from a path to its server;
//! - [`fs`]: the calls that name a path, and `close()`, `lseek()`;
//! - [`fd`]: pipes, duplication, `fcntl()`, directory entries, the
//!   working directory, vectored I/O, truncation, modes, the mask,
//!   process groups, sleeping and waiting for a signal;
//! - [`stat`]: `fstat()`, and FreeBSD's `struct stat` from QNX's;
//! - [`cred`]: the process's IDs and credentials;
//! - [`proc`]: `fork()`, `execve()` and `wait4()`, the process manager's;
//! - [`time`]: the clocks, and the CPUs;
//! - [`tty`]: `ioctl()`, the terminal requests as QNX's device commands;
//! - [`signal`]: the signal numbers and sets of both systems, `sigprocmask()`, `kill()`;
//! - [`sigaction`]: `sigaction()` and the trampoline that turns QNX's
//!   signal frame into FreeBSD's for a handler;
//! - [`thread`]: libthr's thread calls, over OsCraft's own kernel calls;
//! - [`umtx`]: `_umtx_op()`, FreeBSD's locks, over OsCraft's futex;
//! - [`mem`]: `mmap()` and its family, as memory-manager messages;
//! - [`sysctl`]: the few `sysctl()` values libc asks for;
//! - [`process`]: the process calls;
//! - `stubs`, generated by `tools/gen-stubs.py`: every other call, failing
//!   with ENOSYS, and the weak aliases.

