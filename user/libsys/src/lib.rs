/// FreeBSD's `SIGABRT`.
const SIGABRT: i32 = 6;

#[panic_handler]
fn panic(_: &core::panic::PanicInfo) -> ! {
    // The status a shell reports for a SIGABRT; an exit, because signals
    // may be what is broken.
    process::exit_now(128 + SIGABRT)
}
