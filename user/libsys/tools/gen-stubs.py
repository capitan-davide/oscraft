#!/usr/bin/env python3
"""Generate src/stubs.rs: a stub for every FreeBSD system call this crate
does not implement by hand, which reports the call on the standard error
and fails with ENOSYS, and the weak aliases FreeBSD's stubs carry.

    gen-stubs.py <freebsd-src> > src/stubs.rs   (from any directory)

The names come from sys/sys/syscall.mk (the freebsdN_ compatibility
entries left out, as lib/libsys/aarch64/Makefile.sys leaves them out);
which calls get a plain-name alias from lib/libsys/Makefile.sys (PSEUDO
and INTERPOSED do not); the versioned compatibility names from
lib/libc/include/compat.h. The hand-written ones are those `src/*.rs`
define as `__sys_<name>`."""
import glob, os, re, sys

src = sys.argv[1]
names = re.findall(r"([A-Za-z_0-9]+)\.o", open(f"{src}/sys/sys/syscall.mk").read())
names = [n for n in names if not re.match(r"freebsd[467]_", n)]
mk = open(f"{src}/lib/libsys/Makefile.sys").read()
def block(var):
    m = re.search(var + r"\s*\+?=\s*((?:[^\n]*\\\n)*[^\n]*)", mk)
    return set(re.findall(r"[A-Za-z_0-9]+", m.group(1).replace("\\", " "))) if m else set()
pseudo = block("PSEUDO") | block("INTERPOSED")
done = set()
for f in glob.glob(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "*.rs")):
    if f.endswith("stubs.rs"):
        continue
    done |= set(re.findall(r"fn __sys_([A-Za-z_0-9]+)\(", open(f).read()))

print("//! Generated by tools/gen-stubs.py: do not edit. The system calls not")
print("//! implemented by hand, each a stub that says so on the standard error")
print("//! and fails with ENOSYS, so that a program's first missing call is")
print("//! visible; and the weak aliases.")
print("#![allow(non_snake_case, missing_docs)]\n")
print("use crate::errno::not_implemented;\n")
for n in sorted(names):
    if n in done:
        continue
    print(f"#[unsafe(no_mangle)]\npub extern \"C\" fn __sys_{n}() -> isize {{\n    not_implemented(\"{n}\")\n}}")
print()
# Aliases: `_name` for every call; `name` unless PSEUDO or INTERPOSED.
# A tail call in assembly, so that the alias is weak and the same code.
# The versioned compatibility symbols libc's Symbol.map expects of the
# older calls (lib/libc/include/compat.h): stat@FBSD_1.0 is freebsd11_stat.
compat = re.findall(r"__sym_compat\((\w+),\s*(\w+),\s*([\w.]+)\)", open(f"{src}/lib/libc/include/compat.h").read())
print("core::arch::global_asm!(")
for n in sorted(names):
    aliases = [f"_{n}"] + ([] if n in pseudo else [n])
    for a in aliases:
        print(f"    \".weak {a}\", \".type {a}, %function\", \"{a}: b __sys_{n}\",")
for sym, impl, ver in compat:
    if impl in names:
        print(f"    \".symver {impl}, {sym}@{ver}\",")
print(");")
